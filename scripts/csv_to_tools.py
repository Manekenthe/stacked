#!/usr/bin/env python3
"""
Convert a Framer CMS export (tool.csv + category.csv) into tools.js.

Usage:
    python3 scripts/csv_to_tools.py tool.csv category.csv            # writes ./tools.js
    python3 scripts/csv_to_tools.py tool.csv category.csv -o tools.js

Expected columns
    tool.csv      Slug, Image, Image:alt, Title, Categories, Description, Link
    category.csv  Slug, Title, Featured
"""
import argparse
import csv
import json
import re
import sys
from pathlib import Path

# Display names that differ from the CMS (e.g. fix typos). Keyed by category slug.
LABEL_OVERRIDES = {"accesibility": "Accessibility"}

HEADER = """/* ==========================================================================
   Stacked – tool data  (generated by scripts/csv_to_tools.py from the Framer export)
   You can also edit this file by hand – one tool per line, newest first.

   title       – tool name
   description – one short sentence
   url         – link opened in a new tab (empty = card not clickable)
   image       – thumbnail (16:10). Remote URL or a path in assets/tools/
                 (run scripts/download_images.py to host the images yourself)
   categories  – names from the category bar (the special "All" is implicit)
   ========================================================================== */
"""


def read_csv(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def normalize_url(link):
    link = (link or "").strip()
    if not link:
        return ""
    return link if re.match(r"^[a-z][a-z0-9+.-]*://", link, re.I) else "https://" + link


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tools_csv")
    ap.add_argument("categories_csv")
    ap.add_argument("-o", "--out", default="tools.js")
    args = ap.parse_args()

    labels = {}
    for r in read_csv(args.categories_csv):
        slug = r["Slug"].strip()
        labels[slug] = LABEL_OVERRIDES.get(slug, r["Title"].strip())

    out, unknown, no_link = [], set(), []
    for r in read_csv(args.tools_csv):
        cats = []
        for slug in (r.get("Categories") or "").split(","):
            slug = slug.strip()
            if not slug or slug == "all":
                continue
            if slug in labels:
                cats.append(labels[slug])
            else:
                unknown.add(slug)
        image = (r.get("Image") or "").strip()
        url = normalize_url(r.get("Link"))
        if not url:
            no_link.append(r["Title"])
        out.append({
            "title": r["Title"].strip(),
            "description": (r.get("Description") or "").strip(),
            "url": url,
            "image": image,
            "categories": cats,
        })

    lines = ",\n".join("  " + json.dumps(t, ensure_ascii=False, separators=(", ", ": ")) for t in out)
    Path(args.out).write_text(HEADER + "\nwindow.STACKED_TOOLS = [\n" + lines + "\n];\n", encoding="utf-8")

    print(f"{len(out)} tools written to {args.out}")
    if no_link:
        print(f"{len(no_link)} tools without link: {', '.join(no_link)}")
    if unknown:
        print(f"unknown category slugs (skipped): {', '.join(sorted(unknown))}", file=sys.stderr)


if __name__ == "__main__":
    main()
